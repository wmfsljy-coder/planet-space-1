/* 행성우주과학 Ⅰ-2 — 소단원 잇기 카드
   한 소단원이 뒤 소단원에 넘겨주는 것을 여기 한 곳에 적는다.
   · 넘겨주는 이야기의 결말 아래 '넘겨주기 카드'(sthHandoff)
   · 그것을 쓰는 이야기 맨 앞 '이어받기 카드'(sthBridge) — 앞 소단원을 건너뛰었거나 아직 안 끝냈을 때만 펼쳐진다.
   엔진: ../assets/scope.js. episodes.js·worked.js 다음에 불러온다. */
(function () {
"use strict";

var D01 = [
  "행성은 태양을 한 초점으로 하는 <b>타원</b>을 돈다. 태양에 가장 가까운 곳이 <b>근일점</b>, 가장 먼 곳이 <b>원일점</b>이다. 가까울 때 빠르고 멀 때 느리다(<b>면적 속도 일정</b>).",
  "<b>P² = a³</b> (P: 년, a: AU). 혜성도 같은 법칙을 따른다. 핼리 혜성은 주기 76년이므로 긴반지름이 약 <b>17.8 AU</b>이다.",
  "a³/P² 값은 <b>중심 천체의 질량</b>으로 정해진다. 태양 둘레에서는 1이고, 다른 별 둘레에서는 그 별의 질량(태양 질량 단위)이 된다: <b>a³ = M × P²</b>."
];
var D02 = [
  "<b>평균 밀도 = 질량 ÷ 부피(4/3·π·r³)</b>. 밀도가 크면(3 g/cm³ 넘게) 암석·금속이 주를 이루고, 1 g/cm³ 안팎이면 기체·얼음이 많거나 속이 빈 천체다.",
  "지구형 행성은 밀도가 약 <b>3.9~5.5 g/cm³</b>, 목성형 행성은 약 <b>0.7~1.6 g/cm³</b>로 뚜렷이 갈린다."
];

/* 01 → 넘겨주기 */
window.sthHandoff({
  ep: "ep1", title: "이 이야기에서 챙겨 갈 세 줄", lines: D01,
  note: "02 「행성과 소천체」에서 핼리 혜성의 타원 궤도를 따라가며 꼬리를 살피고, 03 「외계 행성계 탐사」에서는 같은 조화 법칙으로 다른 별을 도는 행성의 궤도 반지름을 구합니다."
});

/* 02 ← 01 */
window.sthBridge({
  ep: "ep2", need: "01", doneKey: "ep1",
  lines: [D01[0], D01[1], "이 이야기의 마지막 조사에서 핼리 혜성이 근일점에서 원일점까지 타원 궤도를 도는 동안 꼬리가 어디를 향하는지 봅니다."],
  check: { q: "공전 주기가 8년인 소행성의 궤도 긴반지름은?", options: ["2 AU", "4 AU", "8 AU", "16 AU"], a: 1, why: "P² = 64 = a³ 이므로 a = 4 AU입니다." }
});

/* 02 → 넘겨주기 */
window.sthHandoff({
  ep: "ep2", title: "이 이야기에서 챙겨 갈 두 줄", lines: D02,
  note: "03 「외계 행성계 탐사」에서 시선 속도법(질량)과 통과법(반지름)을 합쳐 외계 행성의 <b>평균 밀도</b>를 구하고, 기체 행성인지 가립니다."
});

/* 03 ← 01 */
window.sthBridge({
  ep: "ep3", need: "01", doneKey: "ep1",
  lines: [D01[2], "이 이야기에서는 별이 흔들리는 주기(행성의 공전 주기)와 별의 질량을 넣어, 보이지 않는 행성의 <b>궤도 반지름</b>을 구합니다."],
  check: { q: "공전 주기가 같을 때, 중심 별의 질량이 8배이면 행성의 궤도 긴반지름은?", options: ["같다", "2배", "8배", "64배"], a: 1, why: "a³ = M × P² 이므로 a³이 8배, a는 2배입니다." }
});

/* 03 ← 02 */
window.sthBridge({
  ep: "ep3", need: "02", doneKey: "ep2",
  lines: [D02[0], D02[1], "이 이야기에서는 행성의 질량과 반지름을 따로 재어 평균 밀도를 구하고, 물보다 가벼운 <b>부풀어 오른 기체 행성</b>을 찾아냅니다."],
  check: { q: "질량은 같고 반지름이 2배인 행성의 평균 밀도는?", options: ["2배", "같다", "1/2", "1/8"], a: 3, why: "부피가 2³ = 8배가 되므로 밀도는 1/8이 됩니다." }
});
})();
