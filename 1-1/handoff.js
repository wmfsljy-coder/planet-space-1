/* 행성우주과학1 Ⅰ-1 — 소단원 잇기 카드
   한 소단원이 뒤 소단원에 넘겨주는 것을 여기 한 곳에 적는다.
   · 넘겨주는 이야기의 결말 아래 '넘겨주기 카드'(sthHandoff)
   · 그것을 쓰는 이야기 맨 앞 '이어받기 카드'(sthBridge) — 앞 소단원을 건너뛰었거나 아직 안 끝냈을 때만 펼쳐진다.
   엔진: ../assets/scope.js. episodes.js·worked.js 다음에 불러온다. */
(function () {
"use strict";

var D01 = [
  "전파와 빛은 <b>초속 약 30만 km</b>로 달린다. 걸리는 시간은 <b>거리 ÷ 속력</b>. 화성까지 편도 약 3분~22분이다.",
  "지구 대기는 <b>X선·자외선과 적외선의 대부분을 흡수</b>한다. 그 빛으로 우주를 보려면 대기 밖의 <b>인공위성·우주 망원경</b>이 있어야 한다."
];
var D02 = [
  "같은 태양 폭발도 <b>세 번 나뉘어</b> 닿는다. 플레어의 X선은 <b>약 8분 20초</b>, 고에너지 입자는 수십 분~수 시간, <b>코로나 질량 방출은 1~3일</b>.",
  "L1 감시 위성(지구에서 약 150만 km)은 플라스마 덩어리를 지구보다 먼저 맞아, 속력에 따라 <b>몇 분~수십 분 앞서</b> 경보를 준다. <b>미리 알수록 대비할 시간이 생긴다.</b>"
];

/* 01 → 넘겨주기 */
window.sthHandoff({
  ep: "ep1", title: "이 이야기에서 챙겨 갈 두 줄", lines: D01,
  note: "02 「태양 활동 감시 시스템」에서 태양 폭풍의 도착 시간을 같은 셈(<b>거리 ÷ 속력</b>)으로 구하고, 태양을 지켜보는 <b>감시 위성</b>이 다시 나옵니다."
});

/* 02 ← 01 */
window.sthBridge({
  ep: "ep2", need: "01", doneKey: "ep1",
  lines: [D01[0], D01[1], "이 이야기에서는 태양에서 지구까지(1 AU, 약 1억 4,960만 km) 오는 X선·입자·플라스마의 도착 시간을 같은 셈으로 구합니다."],
  check: { q: "1 AU(약 1억 5천만 km)를 빛의 속력(약 30만 km/s)으로 건너오는 데 걸리는 시간은?", options: ["약 8초", "약 8분 20초", "약 8시간", "약 8일"], a: 1, why: "1억 5천만 ÷ 30만 = 500초, 약 8분 20초입니다." }
});

/* 02 → 넘겨주기 */
window.sthHandoff({
  ep: "ep2", title: "이 이야기에서 챙겨 갈 두 줄", lines: D02,
  note: "03 「지구 접근 천체 감시」의 마지막 서술에서 태양 폭풍과 소행성, 두 우주 위험의 <b>경보 시간</b>을 견줍니다."
});

/* 03 ← 02 */
window.sthBridge({
  ep: "ep3", need: "02", doneKey: "ep2",
  lines: [D02[0], D02[1], "이 이야기의 소행성은 <b>몇 년~수십 년</b> 앞서 찾아낼 수도 있습니다. 결말의 서술에서 두 위험의 경보 시간을 견줍니다."],
  check: { q: "같은 태양 폭발에서 지구에 가장 늦게 닿는 것은?", options: ["플레어의 X선", "고에너지 입자", "코로나 질량 방출"], a: 2, why: "플라스마 덩어리는 초속 수백~수천 km라서 1 AU를 건너는 데 하루에서 사흘이 걸립니다." }
});
})();
